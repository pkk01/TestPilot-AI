import { TestCase } from '@/types/generation.types';

export interface ProjectFile {
    path: string;
    content: string;
}

// --------------- Templates ---------------

function generatePackageJson(): string {
    return JSON.stringify(
        {
            name: 'automation-playwright',
            version: '1.0.0',
            description: 'Playwright automation project generated by TestPilot AI',
            scripts: {
                test: 'npx playwright test',
                'test:headed': 'npx playwright test --headed',
                'test:ui': 'npx playwright test --ui',
                report: 'npx playwright show-report',
            },
            devDependencies: {
                '@playwright/test': '^1.42.0',
            },
        },
        null,
        2
    );
}

function generatePlaywrightConfig(): string {
    return `import { defineConfig, devices } from '@playwright/test';

export default defineConfig({
    testDir: './tests',
    fullyParallel: true,
    forbidOnly: !!process.env.CI,
    retries: process.env.CI ? 2 : 0,
    workers: process.env.CI ? 1 : undefined,
    reporter: 'html',
    use: {
        baseURL: 'http://localhost:3000',
        trace: 'on-first-retry',
        screenshot: 'only-on-failure',
    },
    projects: [
        {
            name: 'chromium',
            use: { ...devices['Desktop Chrome'] },
        },
        {
            name: 'firefox',
            use: { ...devices['Desktop Firefox'] },
        },
        {
            name: 'webkit',
            use: { ...devices['Desktop Safari'] },
        },
    ],
});
`;
}

// --------------- Main Generator ---------------

export function generatePlaywrightProject(
    gherkin: string | null,
    stepDefs: string | null,
    testCases: TestCase[] | null
): ProjectFile[] {
    const files: ProjectFile[] = [];
    const root = 'automation-playwright';

    // package.json
    files.push({ path: `${root}/package.json`, content: generatePackageJson() });

    // playwright.config.ts
    files.push({ path: `${root}/playwright.config.ts`, content: generatePlaywrightConfig() });

    // Test spec file — convert Gherkin/test cases into Playwright tests
    const specContent = generateSpecFromArtifacts(gherkin, testCases);
    files.push({ path: `${root}/tests/tests.spec.ts`, content: specContent });

    // If Gherkin exists, include it for reference
    if (gherkin) {
        files.push({ path: `${root}/tests/features/tests.feature`, content: gherkin });
    }

    // README
    files.push({
        path: `${root}/README.md`,
        content: `# Automation Project — Playwright

Generated by **TestPilot AI**

## Setup
\`\`\`bash
npm install
npx playwright install
\`\`\`

## Run Tests
\`\`\`bash
npx playwright test
\`\`\`

## Run with UI
\`\`\`bash
npx playwright test --ui
\`\`\`

## View Reports
\`\`\`bash
npx playwright show-report
\`\`\`
`,
    });

    return files;
}

// --------------- Spec Generator ---------------

function generateSpecFromArtifacts(
    gherkin: string | null,
    testCases: TestCase[] | null
): string {
    const imports = `import { test, expect } from '@playwright/test';\n\n`;

    // If we have Gherkin, parse scenarios from it
    if (gherkin) {
        return imports + generateSpecFromGherkin(gherkin);
    }

    // Otherwise build from test cases
    if (testCases?.length) {
        return imports + generateSpecFromTestCases(testCases);
    }

    // Bare fallback
    return `${imports}test.describe('Generated Tests', () => {
    test('sample test', async ({ page }) => {
        // TODO: Implement your test
        await page.goto('/');
        await expect(page).toHaveTitle(/.*/);
    });
});
`;
}

function generateSpecFromGherkin(gherkin: string): string {
    // Parse Gherkin to extract Feature name and Scenarios
    const featureMatch = gherkin.match(/Feature:\s*(.+)/);
    const featureName = featureMatch?.[1]?.trim() || 'Generated Tests';

    // Split into scenarios
    const scenarioBlocks = gherkin.split(/Scenario(?:\s+Outline)?:\s*/);
    scenarioBlocks.shift(); // Remove the Feature preamble

    if (scenarioBlocks.length === 0) {
        return `test.describe('${escapeTs(featureName)}', () => {
    test('sample test', async ({ page }) => {
        await page.goto('/');
        // TODO: Implement test from Gherkin
    });
});
`;
    }

    const tests = scenarioBlocks.map((block) => {
        const lines = block.trim().split('\n');
        const scenarioName = lines[0]?.trim() || 'Unnamed scenario';
        const steps = lines
            .slice(1)
            .map((l) => l.trim())
            .filter((l) => /^(Given|When|Then|And|But)\s/.test(l));

        const stepComments = steps.map((s) => `        // ${s}`).join('\n');

        return `    test('${escapeTs(scenarioName)}', async ({ page }) => {
${stepComments}
        // TODO: Implement automation steps
        await page.goto('/');
    });`;
    });

    return `test.describe('${escapeTs(featureName)}', () => {
${tests.join('\n\n')}
});
`;
}

function generateSpecFromTestCases(testCases: TestCase[]): string {
    const tests = testCases.map((tc) => {
        const stepComments = tc.steps.map((s) => `        // Step: ${s}`).join('\n');
        const name = tc.title || `Test ${tc.id}`;

        return `    test('${escapeTs(name)}', async ({ page }) => {
        // Preconditions: ${tc.preconditions || 'None'}
${stepComments}
        // Expected: ${tc.expected_result}
        await page.goto('/');
        // TODO: Implement automation steps
    });`;
    });

    return `test.describe('Generated Tests', () => {
${tests.join('\n\n')}
});
`;
}

function escapeTs(s: string): string {
    return s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}
