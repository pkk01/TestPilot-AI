'use client';

import { validateRequirement, ValidationResult } from '@/lib/security/requirementValidator';
import { AlertCircle, HelpCircle, Lightbulb, MessageSquareOff, ShieldX, Sparkles } from 'lucide-react';
import { useEffect, useRef, useState } from 'react';
import { LoaderFive } from '../ui/loader';

interface RequirementInputProps {
    onGenerate: (requirement: string) => void;
    onInvalidInput?: (result: ValidationResult) => void;
    isLoading: boolean;
    activeTab: string;
    initialRequirement?: string;
    autoGenerate?: boolean;
    isRateLimited?: boolean;
}

const MAX_CHARS = 3000;

const PLACEHOLDER = `Example:
User should be able to log into the application using a valid email and password.

• Invalid credentials should display an error message.
• After 5 failed attempts, the account should be locked for 15 minutes.
• Users can reset their password via email verification.`;

const CATEGORY_ICONS: Record<string, typeof MessageSquareOff> = {
    casual_chat: MessageSquareOff,
    gibberish: ShieldX,
    too_vague: HelpCircle,
    off_topic: ShieldX,
    single_word: HelpCircle,
    question_only: HelpCircle,
};

const EXAMPLE_REQUIREMENTS = [
    'User should be able to log in using email and password',
    'System should send a password reset link via email',
    'Shopping cart should update total when item quantity changes',
    'After 3 failed login attempts, show CAPTCHA verification',
    'Admin should be able to deactivate user accounts',
];

export default function RequirementInput({
    onGenerate,
    onInvalidInput,
    isLoading,
    activeTab,
    initialRequirement,
    autoGenerate = false,
    isRateLimited = false,
}: RequirementInputProps) {
    const [requirement, setRequirement] = useState('');
    const [error, setError] = useState('');
    const [rejection, setRejection] = useState<ValidationResult | null>(null);
    const hasSeededInput = useRef(false);
    const hasAutoGenerated = useRef(false);

    useEffect(() => {
        if (!initialRequirement || hasSeededInput.current) return;
        setRequirement(initialRequirement);
        hasSeededInput.current = true;
    }, [initialRequirement]);

    useEffect(() => {
        if (!autoGenerate || hasAutoGenerated.current || isLoading || isRateLimited) return;

        const trimmedRequirement = requirement.trim();
        if (trimmedRequirement.length < 10) return;

        // Validate before auto-generating
        const validation = validateRequirement(trimmedRequirement);
        if (!validation.valid) {
            setRejection(validation);
            onInvalidInput?.(validation);
            return;
        }

        hasAutoGenerated.current = true;
        setError('');
        setRejection(null);
        onGenerate(trimmedRequirement);
    }, [autoGenerate, isLoading, isRateLimited, onGenerate, onInvalidInput, requirement]);

    const handleSubmit = () => {
        if (isRateLimited) {
            setError('Daily AI limit reached. Your quota resets tomorrow.');
            setRejection(null);
            return;
        }

        const trimmed = requirement.trim();

        if (trimmed.length < 10) {
            setError('Please enter at least 10 characters describing your requirement.');
            setRejection(null);
            return;
        }

        // Smart validation
        const validation = validateRequirement(trimmed);
        if (!validation.valid) {
            setError('');
            setRejection(validation);
            onInvalidInput?.(validation);
            return;
        }

        setError('');
        setRejection(null);
        onGenerate(trimmed);
    };

    const handleUseExample = (example: string) => {
        setRequirement(example);
        setRejection(null);
        setError('');
    };

    const charCount = requirement.length;
    const isOverLimit = charCount > MAX_CHARS;

    const getButtonLabel = () => {
        if (isLoading) return 'Generating...';
        switch (activeTab) {
            case 'test_cases': return 'Generate Test Cases';
            case 'gherkin': return 'Generate Gherkin';
            case 'step_defs': return 'Generate Step Defs';
            default: return 'Generate';
        }
    };

    const RejectionIcon = rejection?.category ? CATEGORY_ICONS[rejection.category] || ShieldX : ShieldX;

    return (
        <div className="flex flex-col gap-4 card-rich bg-gradient-to-r from-indigo-500/10 to-cyan-500/10 border border-indigo-500/20 p-6">
            <div className="text-center">
                <label className="block text-sm font-semibold text-foreground mb-1.5">
                    Software Requirement
                </label>
                <p className="text-sm text-gray-400 mb-4">
                    Paste your requirement, user story, or feature description below.
                </p>
                <div className="relative">
                    <textarea
                        value={requirement}
                        onChange={(e) => {
                            setRequirement(e.target.value);
                            if (error) setError('');
                            if (rejection) setRejection(null);
                        }}
                        placeholder={PLACEHOLDER}
                        disabled={isLoading}
                        rows={14}
                        className={`
                      w-full bg-[#0B1220] border rounded-xl px-4 py-3
                      text-foreground placeholder:text-gray-500
                      text-sm resize-none
                      focus:outline-none focus:ring-2 transition-colors duration-150
              disabled:opacity-50 disabled:cursor-not-allowed
              ${rejection
                            ? 'border-amber-500/60 focus:border-amber-500 focus:ring-amber-500/20'
                            : isOverLimit
                                ? 'border-red-500 focus:border-red-500 focus:ring-red-500/20'
                                : 'border-gray-700 focus:border-indigo-500 focus:ring-indigo-500/20'
                        }
            `}
                    />
                </div>

                {/* Char counter */}
                <div className="flex items-center justify-between mt-2">
                    <div>
                        {error && (
                            <p className="flex items-center gap-1.5 text-xs text-red-400">
                                <AlertCircle className="w-3.5 h-3.5" />
                                {error}
                            </p>
                        )}
                    </div>
                    <span className={`text-xs ${isOverLimit ? 'text-red-400' : 'text-foreground-subtle'}`}>
                        {charCount.toLocaleString()} / {MAX_CHARS.toLocaleString()}
                    </span>
                </div>
            </div>

            {/* ── Rejection Banner ─────────────────────────────── */}
            {rejection && (
                <div className="animate-fade-in rounded-xl overflow-hidden">
                    {/* Main rejection message */}
                    <div className="bg-amber-950/30 border border-amber-800/40 rounded-xl p-4">
                        <div className="flex items-start gap-3">
                            <div className="w-9 h-9 rounded-lg bg-amber-500/15 flex items-center justify-center flex-shrink-0 mt-0.5">
                                <RejectionIcon className="w-4.5 h-4.5 text-amber-400" />
                            </div>
                            <div className="flex-1 min-w-0">
                                <p className="text-sm font-semibold text-amber-300 mb-1">
                                    Not a valid requirement
                                </p>
                                <p className="text-xs text-amber-200/70 leading-relaxed">
                                    {rejection.reason}
                                </p>
                                {rejection.suggestion && (
                                    <div className="flex items-start gap-2 mt-3 bg-amber-900/20 rounded-lg p-2.5">
                                        <Lightbulb className="w-3.5 h-3.5 text-amber-400/80 flex-shrink-0 mt-0.5" />
                                        <p className="text-xs text-amber-200/60 leading-relaxed">
                                            {rejection.suggestion}
                                        </p>
                                    </div>
                                )}

                                {/* Quick-use example requirements */}
                                <div className="mt-3 pt-3 border-t border-amber-800/30">
                                    <p className="text-[11px] font-medium text-amber-400/60 uppercase tracking-wider mb-2">
                                        Try one of these
                                    </p>
                                    <div className="flex flex-col gap-1.5">
                                        {EXAMPLE_REQUIREMENTS.slice(0, 3).map((example, i) => (
                                            <button
                                                key={i}
                                                onClick={() => handleUseExample(example)}
                                                className="text-left text-xs text-amber-100/60 hover:text-amber-100 
                                                    bg-amber-900/15 hover:bg-amber-900/30 
                                                    px-3 py-2 rounded-lg transition-all duration-150
                                                    border border-transparent hover:border-amber-700/40
                                                    cursor-pointer"
                                            >
                                                <span className="text-amber-500/60 mr-1.5">→</span>
                                                {example}
                                            </button>
                                        ))}
                                    </div>
                                </div>
                            </div>
                        </div>
                    </div>
                </div>
            )}

            <button
                onClick={handleSubmit}
                disabled={isLoading || isRateLimited || isOverLimit || requirement.trim().length < 10}
                className="btn-primary w-full flex items-center justify-center gap-2 py-3 disabled:opacity-70"
            >
                {isLoading ? (
                    <>
                        <LoaderFive size="sm" text="" className="gap-0" />
                        <span>Generating...</span>
                    </>
                ) : (
                    <>
                        <Sparkles className="w-4 h-4" />
                        <span>{getButtonLabel()}</span>
                    </>
                )}
            </button>

            {isLoading && (
                <div className="card-rich p-4 animate-fade-in border-primary/20 bg-primary/5">
                    <div className="flex items-center gap-4">
                        <LoaderFive size="sm" text="" className="flex-shrink-0" />
                        <p className="text-sm text-foreground font-medium">
                            AI is analyzing your requirement and generating artifacts...
                        </p>
                    </div>
                </div>
            )}
        </div>
    );
}
